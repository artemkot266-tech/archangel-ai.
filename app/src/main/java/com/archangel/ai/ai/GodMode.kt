object GodMode {
    const val MAX_TOKENS = 2500

    fun prompt(role: GodRole) = buildString {
        appendLine()
        appendLine("=== РЕЖИМ БОГА ===")
        appendLine("Ты в расширенном режиме: думай глубже обычного, рассуждай по шагам про себя и проверяй выводы перед ответом.")
        appendLine("Начинай ответ с главного в 1–2 предложениях (эту часть озвучат вслух), затем подробности, если они нужны.")
        appendLine("Ты собеседник, а не справочник: помни контекст разговора, задавай встречный вопрос, когда это уместно.")
        appendLine("Если пользователь прислал фото задачи, документа или вещи — разбери его подробно.")
        appendLine("Медицина, право, финансы: давай полезную информацию, но отмечай, когда нужен специалист.")
        appendLine(role.prompt)
    }

    /** Что озвучить из длинного ответа: первые 2–3 предложения, остальное — на экране. */
    fun spoken(text: String, maxChars: Int = 420): String {
        val plain = text.replace(Regex("[*#_`>]+"), "").replace(Regex("\\s+"), " ").trim()
        if (plain.length <= maxChars) return plain
        val sentences = Regex("(?<=[.!?…])\\s+").split(plain)
        val out = StringBuilder()
        for (s in sentences) {
            if (out.length + s.length > maxChars && out.isNotEmpty()) break
            if (out.isNotEmpty()) out.append(' ')
            out.append(s)
        }
        val head = if (out.isEmpty()) plain.take(maxChars) else out.toString()
        return "$head Подробности — на экране."
    }

    /** Подсказка для «подведи итог»: краткое резюме + факты для памяти отдельными строками. */
    const val SUMMARY_PROMPT =
        "Подведи итог нашего разговора: 3–5 пунктов — что обсудили и к чему пришли, и следующий шаг. " +
            "Затем, если пользователь сообщил о себе что-то важное для будущих разговоров (цели, планы, предпочтения), " +
            "добавь в конце строки вида «ЗАПОМНИТЬ: …» — по одному факту на строку, максимум 3. " +
            "Не записывай пароли, номера документов и карт, а также чувствительные подробности о здоровье."

    /** Разделяет итог и факты для памяти. */
    fun splitSummary(text: String): Pair<String, List<String>> {
        val lines = text.lines()
        val facts = lines.filter { it.trim().startsWith("ЗАПОМНИТЬ:") }
            .map { it.trim().removePrefix("ЗАПОМНИТЬ:").trim() }.filter { it.isNotEmpty() }.take(3)
        val body = lines.filterNot { it.trim().startsWith("ЗАПОМНИТЬ:") }.joinToString("\n").trim()
        return body to facts
    }
}
