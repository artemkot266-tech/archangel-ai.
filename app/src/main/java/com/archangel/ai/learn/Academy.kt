    fun byId(id: String) = lessons.firstOrNull { it.id == id }

    /**
     * Подбирает урок по фразе пользователя. Для пополнения — по названию биржи.
     * null — подходящего урока нет (тогда отвечает «мозг»).
     */
    fun find(query: String): Lesson? {
        val q = " " + query.lowercase().replace('ё', 'е') + " "
        val depositIntent = listOf("пополн", "завести", "закинуть", "внести", "депозит", "купить usdt", "купить крипт").any { it in q }
        val exchange = listOf("deposit_binance", "deposit_bybit", "deposit_okx", "deposit_whitebit")
            .mapNotNull { byId(it) }.firstOrNull { l -> l.keywords.any { it in q } }
        if (depositIntent) return exchange ?: byId("deposit_choose")
        if (exchange != null && listOf("p2p", "п2п", "карт", "гривн").any { it in q }) return exchange
        return lessons.map { l -> l to l.keywords.count { it in q } }
            .filter { it.second > 0 }
            .maxByOrNull { it.second }?.first
    }
